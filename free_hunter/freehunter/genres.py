"""ジャンル分類（キーワード辞書）。上から順に最初に当たったものを採用。"""
from __future__ import annotations

import re

GENRES: list[tuple[str, str]] = [
    ("旅行・体験", r"旅行|宿泊|ホテル|招待|チケット|ツアー|体験|ライブ|観戦"),
    ("家電・ガジェット", r"家電|iPhone|iPad|PS5|Switch|スイッチ|AirPods|ルンバ|ダイソン|Dyson|テレビ|カメラ|ドライヤー|空気清浄|パソコン|PC"),
    ("商品券・ギフト券", r"ギフト券|商品券|QUOカード|クオカード|Amazon|図書カード|ギフトカード|ポイント|PayPay|現金|デジタルギフト"),
    ("食品・飲料", r"食品|飲料|ビール|酒|ワイン|お米|精米|肉|牛|カニ|スイーツ|お菓子|コーヒー|ジュース|ミネラルウォーター|詰め合わせ|グルメ|ラーメン"),
    ("美容・コスメ", r"コスメ|化粧|美容|スキンケア|シャンプー|香水|ヘアケア"),
    ("日用品・生活", r"日用品|洗剤|タオル|寝具|キッチン|調理|生活"),
    ("ファッション", r"バッグ|財布|服|アパレル|スニーカー|腕時計|アクセサリー"),
    ("ホビー・本", r"書籍|図書|漫画|コミック|グッズ|フィギュア|ゲーム|おもちゃ"),
    ("子ども・ベビー", r"ベビー|子ども|子供|キッズ|赤ちゃん"),
]


def classify_genre(*texts: str | None) -> str:
    t = " ".join(x for x in texts if x)
    for name, pat in GENRES:
        if re.search(pat, t, re.IGNORECASE):
            return name
    return "その他"
